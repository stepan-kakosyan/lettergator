def get_existing_msgids(path):
    with open(path, encoding='utf-8') as f:
        content = f.read()
    return set(re.findall(r'^msgid "(.+?)"', content, re.MULTILINE))


def append_entries(path, lang_idx):
    """lang_idx: 1=en, 2=ru, 3=hy (index into tuple)"""
    existing = get_existing_msgids(path)
    lines = []
    for entry in NEW_ENTRIES:
        msgid = entry[0]
        msgstr = entry[lang_idx]
        if msgid == "__SECTION__":
            lines.append(f"\n{entry[1]}\n")
        elif msgid not in existing:
            esc_id = msgid.replace('"', '\\"')
            esc_str = msgstr.replace('"', '\\"')
            lines.append(f'\nmsgid "{esc_id}"\nmsgstr "{esc_str}"\n')

    with open(path, 'a', encoding='utf-8') as f:
        for line in lines:
            f.write(line)
    print(f"Appended {len([l for l in lines if 'msgid' in l])} entries to {path}")


append_entries('locale/en/LC_MESSAGES/django.po', 1)
append_entries('locale/ru/LC_MESSAGES/django.po', 2)
append_entries('locale/hy/LC_MESSAGES/django.po', 3)
print("Done!")
